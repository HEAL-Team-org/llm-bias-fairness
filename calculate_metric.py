#!/usr/bin/env python3
"""
CLIP Directional Similarity — Metric Calculator (SigLIP 2 Giant)
=================================================================

Computes the directional similarity between RAG-enhanced and base prompts
using embeddings from **google/siglip2-giant-opt-patch16-384** (2 B params,
ViT-Giant/16 @ 384 px, trained on WebLI).

Metric (StyleGAN-NADA / Gal et al., 2021)
------------------------------------------

    delta_T   = norm( embed_text(enhanced) − embed_text(base) )
    delta_I_i = norm( embed_image(enhanced_i) − embed_image(base_i) )
    score_i   = dot( delta_T, delta_I_i )          ∈ [−1, +1]
    S_dir     = mean( score_i )

    +1 → visual shift perfectly mirrors textual shift
     0 → orthogonal (no correlation)
    −1 → opposite directions

Assumes images have already been generated by generate_images.py.
Images are expected at:
    outputs/directional_similarity/<model>/row_<ID>/base_seed<SEED:05d>.png
    outputs/directional_similarity/<model>/row_<ID>/enhanced_seed<SEED:05d>.png

Model
-----
    google/siglip2-giant-opt-patch16-384
    • ViT-Giant/16, image size 384×384
    • 1152-dim embeddings
    • Loaded in float16 → ~4 GB on one A100; fits easily alongside Qwen on
      a separate GPU (or in a separate process when Qwen has released VRAM).

Usage
-----
    # evaluate all rows using cached images
    python calculate_metric.py

    # specify a different image directory or results output dir
    python calculate_metric.py --image-dir outputs/directional_similarity --results-dir results

    # run metric on CUDA device 1
    python calculate_metric.py --device cuda:1

    # choose which enhanced prompt variant matches the generated images
    python calculate_metric.py --enhanced-idx 0

CLI flags
---------
  --csv             prompts CSV  (default: inputs/prompts.csv)
  --image-dir       root folder with generated images (default: outputs/directional_similarity)
  --results-dir     where to write JSON + CSV results (default: results)
  --device          torch device for SigLIP2 (default: cuda:0 if available)
  --model           which model's images to evaluate (default: qwen)
  --enhanced-idx    which enhanced prompt variant was used for generation (default: 0)
  --batch-size      images per forward pass through SigLIP2 (default: 8)
"""

from __future__ import annotations

