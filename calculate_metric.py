def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description=(
            "Compute CLIP directional similarity using SigLIP 2 Giant "
            "on pre-generated images."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument("--csv",          type=Path, default=INPUT_CSV,
                   metavar="PATH",   help="Input prompts CSV.")
    p.add_argument("--image-dir",    type=Path, default=IMAGE_OUTPUT_DIR,
                   metavar="DIR",    help="Root directory containing generated images.")
    p.add_argument("--results-dir",  type=Path, default=RESULTS_DIR,
                   metavar="DIR",    help="Output directory for results.")
    p.add_argument("--device",       type=str,  default=None,
                   metavar="DEVICE", help="Torch device (e.g. cuda:0, cuda:1, cpu).")
    p.add_argument("--model",         type=str,  default=DEFAULT_MODEL,
                   choices=list(MODEL_CONFIGS),
                   help="Which model's generated images to evaluate.")
    p.add_argument("--enhanced-idx", type=int,  default=0,
                   metavar="IDX",    help="Enhanced prompt variant index (0-indexed).")
    p.add_argument("--batch-size",   type=int,  default=DEFAULT_BATCH,
                   metavar="N",      help="Images per SigLIP2 forward pass.")
    return p


def main() -> None:
    args   = _build_parser().parse_args()
    device = torch.device(args.device) if args.device else None
    calculate_directional_similarity(
        csv_path     = args.csv,
        image_dir    = args.image_dir,
        results_dir  = args.results_dir,
        device       = device,
        model_name   = args.model,
        enhanced_idx = args.enhanced_idx,
        batch_size   = args.batch_size,
    )


if __name__ == "__main__":
    main()
