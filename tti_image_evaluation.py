def detect_face(image_paths, SAVE_DETECTED_AT, default_max_size=800, size=300, padding=0.25, dlib_model_dir="dlib_models"):
    """
    Detect faces and save aligned images.

    Args:
        image_paths: List of image file paths
        SAVE_DETECTED_AT: Directory to save detected faces
        default_max_size: Maximum image size for processing
        size: Output face chip size
        padding: Padding around detected face
        dlib_model_dir: Path to dlib models directory
    """
    face_detector = dlib.get_frontal_face_detector()
    # ✅ FIXED: Use parameter instead of global variable
    predictor_path = os.path.join(dlib_model_dir, "shape_predictor_5_face_landmarks.dat")

    if not os.path.exists(predictor_path):
        raise FileNotFoundError(f"Dlib predictor not found at: {predictor_path}")

    sp = dlib.shape_predictor(predictor_path)

    for index, image_path in enumerate(image_paths):
        if index % 100 == 0:
            print('Processing image: %d/%d' % (index, len(image_paths)))
        img = dlib.load_rgb_image(image_path)

        old_height, old_width, _ = img.shape
        if old_width > old_height:
            new_width, new_height = default_max_size, int(default_max_size * old_height / old_width)
        else:
            new_width, new_height = int(default_max_size * old_width / old_height), default_max_size

        img = dlib.resize_image(img, rows=new_height, cols=new_width)

        dets = face_detector(img, 1)
        if len(dets) == 0:
            print("No face detected in: {}".format(image_path))
            continue

        faces = dlib.full_object_detections()
        for rect in dets:
            faces.append(sp(img, rect))

        images = dlib.get_face_chips(img, faces, size=size, padding=padding)
        for idx, image in enumerate(images):
            img_name = os.path.basename(image_path)
            base, ext = os.path.splitext(img_name)
            face_name = os.path.join(SAVE_DETECTED_AT, f"{base}_face{idx}{ext}")
            dlib.save_image(image, face_name)

def is_image_file(path):
    if not os.path.isfile(path):
        return False
    _, ext = os.path.splitext(path.lower())
    return ext in {'.jpg', '.jpeg', '.png', '.bmp'}

